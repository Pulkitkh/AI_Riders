#!/usr/bin/env python3
"""THE canonical evaluation. Every performance number in the deck, the README and
the web viewer is generated by this one command:

    python3 eval/report.py      # prints the tables and writes eval/report.json

What it reports, and why each exists after a senior-jury audit:

  * STRICT per-class precision/recall/F1 — multi-label truth, NO class-equivalence
    credit. This is the headline macro-F1. A wrong class is a wrong class.
  * a SEPARATE host-detection F1 — did we catch that the host is malicious at all,
    regardless of exact class. Reported beside the strict number, never instead.
  * a strict confusion matrix (primary-vs-primary) that can show real off-diagonal.
  * false positives split three ways: FP events, FP hosts, and FPR over benign hosts.
  * false negatives per class.
  * detection-window delay P50/P95/P99 (see the note — this is window latency,
    measured separately from raw processing throughput).
  * calibration quality: ECE and Brier of the calibrated confidence vs outcome.
  * dataset composition and the test-suite count, so the deck cannot drift from it.

Everything is on HELD-OUT captures whose seeds AND jitter were never used to train
the models or fit the calibration.
"""
from __future__ import annotations

import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "eval"))

from prahari.engine import Engine
from prahari.generate import ALL_ATTACKS, TrafficGenerator
from prahari.schema import SEVERITY_BY_CLASS
from common import host_pred, host_truth   # noqa: E402  (eval/common.py)

# Held-out: seeds and jitter never used in training {11,23,37,41} or calibration.
HELD_OUT = [(2001, 0.15), (2002, 0.22), (2003, 0.30), (2004, 0.08), (2005, 0.40),
            (3007, 0.18), (3009, 0.27), (3011, 0.05)]
SEV_RANK = {"critical": 4, "high": 3, "medium": 2, "low": 1}
CAPTURE_SECONDS = 1800


def count_tests() -> dict:
    import re
    counts = {}
    for name in ("test_prahari.py", "test_web.py"):
        p = ROOT / "tests" / name
        n = len(re.findall(r"^def (test_\w+)", p.read_text(encoding="utf-8"), re.M)) if p.exists() else 0
        counts[name] = n
    counts["total"] = sum(v for k, v in counts.items() if k != "total")
    return counts


def ece_brier(conf_correct: list[tuple[float, int]], bins: int = 10):
    """Expected Calibration Error and Brier score over (confidence, correct)."""
    if not conf_correct:
        return 0.0, 0.0
    n = len(conf_correct)
    brier = sum((c - y) ** 2 for c, y in conf_correct) / n
    buckets = defaultdict(list)
    for c, y in conf_correct:
        buckets[min(int(c * bins), bins - 1)].append((c, y))
    ece = 0.0
    for b in buckets.values():
        avg_conf = sum(c for c, _ in b) / len(b)
        acc = sum(y for _, y in b) / len(b)
        ece += len(b) / n * abs(avg_conf - acc)
    return ece, brier


def main() -> int:
    scored = sorted(ALL_ATTACKS)                # 8 ground-truth attack classes
    labels = scored + ["benign"]
    conf = defaultdict(Counter)                 # truth primary -> Counter(pred primary)
    tpc, fnc, fpc = Counter(), Counter(), Counter()
    comp = Counter()
    total_flows = total_alerts = 0
    benign_hosts = benign_flagged = fp_events = 0
    anom_on_attack = anom_on_benign = 0
    # host-detection (any attack class vs any true attack)
    hd_tp = hd_fp = hd_fn = 0
    latencies: list[float] = []
    cal_pairs: list[tuple[float, int]] = []     # (calibrated confidence, correct)
    proc_wall = 0.0                             # wall-clock compute time (all captures)

    for seed, jitter in HELD_OUT:
        flows = TrafficGenerator(seed=seed, jitter=jitter).capture(CAPTURE_SECONDS, classes=ALL_ATTACKS)
        engine = Engine(window=60.0)
        alerts = engine.run(flows)
        total_flows += len(flows)
        total_alerts += len(alerts)
        latencies.extend(engine.stats.latencies_ms)
        proc_wall += engine.stats.wall_seconds
        for f in flows:
            comp[f.label] += 1
        truth = host_truth(flows)
        attack_pred, full_pred, primary = host_pred(alerts)

        for host, tset in truth.items():
            preds = attack_pred.get(host, set())
            if not tset:                                    # benign host
                benign_hosts += 1
                if preds:
                    benign_flagged += 1
                    fp_events += len(preds)
                    for p in preds:
                        fpc[p] += 1
                    hd_fp += 1
                if "anomalous_traffic" in full_pred.get(host, set()):
                    anom_on_benign += 1
                continue
            # attack host — strict per-class, multi-label, NO equivalence
            for c in scored:
                if c in tset and c in preds:
                    tpc[c] += 1
                elif c in tset and c not in preds:
                    fnc[c] += 1
                elif c not in tset and c in preds:
                    fpc[c] += 1                              # wrong class on an attack host
            if preds & tset:
                hd_tp += 1
            elif tset:
                hd_fn += 1
            if "anomalous_traffic" in full_pred.get(host, set()):
                anom_on_attack += 1
            t_primary = max(tset, key=lambda c: SEV_RANK.get(SEVERITY_BY_CLASS.get(c, "low"), 0))
            conf[t_primary][primary.get(host, "benign")] += 1

        # calibration pairs from the raw alert records
        for a in alerts:
            host = "10.42.0.80" if a.threat_class == "volumetric_ddos" else a.src_ip
            correct = 1 if a.threat_class in truth.get(host, set()) else 0
            cal_pairs.append((a.confidence, correct))

    rows, macro = {}, []
    for c in scored:
        tp, fn, fp = tpc[c], fnc[c], fpc[c]
        prec = tp / (tp + fp) if tp + fp else (1.0 if tp else 0.0)
        rec = tp / (tp + fn) if tp + fn else 0.0
        fpr = fp / benign_hosts if benign_hosts else 0.0
        f1 = 2 * prec * rec / (prec + rec) if prec + rec else 0.0
        macro.append(f1)
        rows[c] = {"tp": tp, "fp": fp, "fn": fn, "precision": round(prec, 3),
                   "recall": round(rec, 3), "f1": round(f1, 3), "fpr": round(fpr, 4)}

    macro_f1 = sum(macro) / len(macro)
    hd_prec = hd_tp / (hd_tp + hd_fp) if hd_tp + hd_fp else 0.0
    hd_rec = hd_tp / (hd_tp + hd_fn) if hd_tp + hd_fn else 0.0
    hd_f1 = 2 * hd_prec * hd_rec / (hd_prec + hd_rec) if hd_prec + hd_rec else 0.0
    fp_host_rate = benign_flagged / benign_hosts if benign_hosts else 0.0
    per_million = total_alerts / total_flows * 1e6 if total_flows else 0.0
    ece, brier = ece_brier(cal_pairs)
    lat = sorted(latencies)

    def pct(p):
        if not lat:
            return 0.0
        k = min(int(round(p / 100.0 * (len(lat) - 1))), len(lat) - 1)
        return round(lat[k], 1)

    tests = count_tests()
    proc_throughput = total_flows / proc_wall if proc_wall else 0.0
    proc_latency_ms = proc_wall / total_flows * 1000.0 if total_flows else 0.0

    # ---- print ----
    print("PRAHARI evaluation report — held-out captures only (strict scoring)")
    print("=" * 76)
    print(f"\nDATASET  {len(HELD_OUT)} captures · {total_flows:,} flows · "
          f"{comp['benign']:,} benign ({comp['benign']/total_flows:.1%}) · "
          f"{total_flows-comp['benign']:,} attack · {benign_hosts} benign hosts")
    print("  per class:", {k: v for k, v in sorted(comp.items())})

    print(f"\n{'class':<20}{'prec':>7}{'recall':>8}{'f1':>7}{'FPR':>8}   tp/fp/fn")
    for c in scored:
        r = rows[c]
        print(f"{c:<20}{r['precision']:>7.3f}{r['recall']:>8.3f}{r['f1']:>7.3f}"
              f"{r['fpr']:>8.3f}   {r['tp']}/{r['fp']}/{r['fn']}")
    print("-" * 76)
    print(f"STRICT macro-F1 (8 classes, no equivalence credit): {macro_f1:.3f}")
    print(f"host-detection F1 (any attack vs any benign)      : {hd_f1:.3f}  "
          f"(P {hd_prec:.3f} / R {hd_rec:.3f})")
    print(f"false positives: {fp_events} events on {benign_flagged}/{benign_hosts} benign hosts "
          f"(host FPR {fp_host_rate:.2%})")
    print(f"alert volume: {per_million:.0f} per million flows "
          f"({total_alerts} alerts / {total_flows:,} flows)")
    print(f"calibration: ECE {ece:.3f} · Brier {brier:.3f}  (n={len(cal_pairs)} alerts)")
    print(f"processing throughput: {proc_throughput:,.0f} flows/s (full pipeline) · "
          f"{proc_latency_ms:.3f} ms/flow compute")
    print(f"detection-window delay (event->alert): p50 {pct(50)} ms · p95 {pct(95)} ms · "
          f"p99 {pct(99)} ms  [bounded by the {60}s window; live default is 5s]")
    print(f"anomaly net (corroborating): {anom_on_attack} attack hosts, {anom_on_benign} benign hosts")
    print(f"test suite: {tests['total']} tests "
          f"({tests.get('test_prahari.py',0)} engine + {tests.get('test_web.py',0)} web)")

    print("\nSTRICT CONFUSION MATRIX  (rows = truth primary, cols = prediction primary)")
    hdr = "".join(f"{c[:8]:>9}" for c in labels)
    print(f"{'true/pred':<20}{hdr}")
    for t in labels:
        line = "".join(f"{conf[t][p]:>9}" for p in labels)
        print(f"{t:<20}{line}")

    out = {
        "dataset": {"captures": len(HELD_OUT), "flows": total_flows,
                    "benign_flows": comp["benign"], "benign_hosts": benign_hosts,
                    "composition": dict(comp), "capture_seconds": CAPTURE_SECONDS},
        "per_class": rows,
        "macro_f1_strict": round(macro_f1, 4),
        "host_detection": {"precision": round(hd_prec, 4), "recall": round(hd_rec, 4),
                           "f1": round(hd_f1, 4), "tp": hd_tp, "fp": hd_fp, "fn": hd_fn},
        "false_positives": {"events": fp_events, "hosts": benign_flagged,
                            "benign_hosts": benign_hosts, "host_fpr": round(fp_host_rate, 4)},
        "alerts_per_million_flows": round(per_million, 1),
        "total_alerts": total_alerts,
        "calibration": {"ece": round(ece, 4), "brier": round(brier, 4), "alerts": len(cal_pairs)},
        "throughput": {"flows_per_sec_full_pipeline": round(proc_throughput, 0),
                       "processing_latency_ms_per_flow": round(proc_latency_ms, 4),
                       "boundary": "full pipeline: parse->detect->fuse->calibrate->ledger"},
        "detection_window_delay_ms": {"p50": pct(50), "p95": pct(95), "p99": pct(99),
                       "window_seconds": 60, "live_window_seconds": 5,
                       "note": "event->alert delay, bounded by the analysis window "
                               "(configurable: 60s batch / 5s live); NOT compute time"},
        "anomaly_net": {"attack_hosts": anom_on_attack, "benign_hosts": anom_on_benign},
        "tests": tests,
        "confusion": {t: dict(conf[t]) for t in labels},
        "labels": labels,
    }
    (ROOT / "eval" / "report.json").write_text(json.dumps(out, indent=2), encoding="utf-8")
    print("\nwrote eval/report.json  (the one source of truth for every headline number)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
